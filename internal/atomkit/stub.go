package atomkit

// Stub is the main.go the atom builder compiles for a logic atom whose package
// is importPath (lld.md FN-084): it calls atomkit.Main on the package's Def.
// The package is imported under the alias atom, so the bytes depend on
// importPath alone; daedalus internal/atombuild holds a byte-identical copy,
// held to testdata/stub-checkmergeconflict.go.golden in both repos.
func Stub(importPath string) []byte {
	return []byte("// Code generated by atomkit.Stub. DO NOT EDIT.\n\n" +
		"package main\n\n" +
		"import (\n" +
		"\t\"dagger/foundry-tools/internal/atomkit\"\n" +
		"\tatom \"" + importPath + "\"\n" +
		")\n\n" +
		"func main() { atomkit.Main(atom.Def) }\n")
}
