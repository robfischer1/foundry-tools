package atomkit

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"os"
	"path/filepath"
	"testing"
)

// goldenStubSum is the sha256 of testdata/stub-checkmergeconflict.go.golden, the
// sum daedalus' copy must equal (UT-483).
const goldenStubSum = "e04b434f395665a8315933e79c434c7cb75db00555026b8cebc3a277b4ea8a42"

const checkMergeConflictPkg = "dagger/foundry-tools/atoms/fleet/check-merge-conflict"

func TestUT_482_StubIsConstantPerImportPath(t *testing.T) {
	want := "// Code generated by atomkit.Stub. DO NOT EDIT.\n\npackage main\n\nimport (\n\t\"dagger/foundry-tools/internal/atomkit\"\n\tatom \"" + checkMergeConflictPkg + "\"\n)\n\nfunc main() { atomkit.Main(atom.Def) }\n"
	a, b := Stub(checkMergeConflictPkg), Stub(checkMergeConflictPkg)
	if string(a) != want || !bytes.Equal(a, b) {
		t.Fatalf("%q", a)
	}
}

// TestUT_483_IT_131_StubIsTheGolden holds Stub to the file daedalus
// internal/atombuild holds a copy of; the sum is what the other repo's test
// compares.
func TestUT_483_IT_131_StubIsTheGolden(t *testing.T) {
	golden, err := os.ReadFile(filepath.Join("testdata", "stub-checkmergeconflict.go.golden"))
	if err != nil {
		t.Fatal(err)
	}
	if got := Stub(checkMergeConflictPkg); !bytes.Equal(got, golden) {
		t.Fatalf("Stub differs from the golden:\n%s", got)
	}
	sum := sha256.Sum256(golden)
	if got := hex.EncodeToString(sum[:]); got != goldenStubSum {
		t.Fatalf("golden sha256 %s, want %s", got, goldenStubSum)
	}
}
