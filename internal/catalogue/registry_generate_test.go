package catalogue

import (
	"bytes"
	"fmt"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

// generate is the source of registry_gen.go for the module at root: every
// atoms/<ns>/<name>/<name>.go as an import and a *atomkit.Def, sorted by id, and
// every atoms/<ns>/<name>.toml as a path and its bytes, sorted by path.
// TestRegistryIsGenerated holds the file to it and, when it is stale, prints
// these bytes; writing them over registry_gen.go is the whole regeneration.
//
// It is a Go program and not a script, and it needs nothing but the tree: the
// package name of each atom is read from its file's package clause.
func generate(root string) ([]byte, error) {
	atomDirs, manifests, err := scan(filepath.Join(root, "atoms"))
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/catalogue (registry_generate_test.go). DO NOT EDIT.\n\npackage catalogue\n\nimport (\n")
	b.WriteString("\t\"dagger/foundry-tools/internal/atomkit\"\n")
	var refs []string
	for _, d := range atomDirs {
		pkg, err := packageOf(filepath.Join(root, "atoms", d, filepath.Base(d)+".go"))
		if err != nil {
			return nil, err
		}
		fmt.Fprintf(&b, "\t%s %q\n", pkg, "dagger/foundry-tools/atoms/"+d)
		refs = append(refs, "&"+pkg+".Def")
	}
	b.WriteString(")\n\n// Defs is every logic atom, sorted by id.\nvar Defs = []*atomkit.Def{\n")
	for _, r := range refs {
		b.WriteString("\t" + r + ",\n")
	}
	b.WriteString("}\n\n// ManifestSources is every command atom's manifest, sorted by path.\nvar ManifestSources = []ManifestSource{\n")
	for _, m := range manifests {
		body, err := os.ReadFile(filepath.Join(root, m))
		if err != nil {
			return nil, err
		}
		fmt.Fprintf(&b, "\t{Path: %s, Body: %s},\n", strconv.Quote(m), strconv.Quote(string(body)))
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

// scan lists the atom directories (as ns/name) and the manifests (as
// atoms/ns/name.toml, relative to the module root) under atoms/, sorted.
// A directory under atoms/<ns>/ that holds no <name>.go is an error: it would
// be an atom nobody registered.
func scan(atomsDir string) (dirs, manifests []string, err error) {
	spaces, err := os.ReadDir(atomsDir)
	if err != nil {
		return nil, nil, err
	}
	for _, ns := range spaces {
		if !ns.IsDir() {
			continue
		}
		names, err := os.ReadDir(filepath.Join(atomsDir, ns.Name()))
		if err != nil {
			return nil, nil, err
		}
		for _, n := range names {
			switch {
			case n.IsDir():
				if _, err := os.Stat(filepath.Join(atomsDir, ns.Name(), n.Name(), n.Name()+".go")); err != nil {
					return nil, nil, fmt.Errorf("atoms/%s/%s holds no %s.go: %w", ns.Name(), n.Name(), n.Name(), err)
				}
				if err := onlyItsOwnFile(filepath.Join(atomsDir, ns.Name(), n.Name()), n.Name()); err != nil {
					return nil, nil, err
				}
				dirs = append(dirs, ns.Name()+"/"+n.Name())
			case strings.HasSuffix(n.Name(), ".toml"):
				manifests = append(manifests, "atoms/"+ns.Name()+"/"+n.Name())
			}
		}
	}
	sort.Strings(dirs)
	sort.Strings(manifests)
	return dirs, manifests, nil
}

// packageOf is the package a Go file declares.
func packageOf(file string) (string, error) {
	f, err := parser.ParseFile(token.NewFileSet(), file, nil, parser.PackageClauseOnly)
	if err != nil {
		return "", err
	}
	return f.Name.Name, nil
}

// onlyItsOwnFile holds an atom's directory to the atom law: <name>.go and its
// _test.go files, and no other Go file. One atom per file; what two atoms share
// lives in an internal package, and what one atom alone needs but cannot hold
// in its file lives in one of its own (the daedalus atom builder refuses the
// directory otherwise, and the atom index freezes).
func onlyItsOwnFile(dir, name string) error {
	files, err := os.ReadDir(dir)
	if err != nil {
		return err
	}
	for _, f := range files {
		n := f.Name()
		if strings.HasSuffix(n, ".go") && !strings.HasSuffix(n, "_test.go") && n != name+".go" {
			return fmt.Errorf("%s holds %s beside %s.go: an atom's directory holds its own file and its tests only", dir, n, name)
		}
	}
	return nil
}
